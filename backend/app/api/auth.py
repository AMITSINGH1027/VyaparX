@router.post(
    "/register",
    response_model=Token,
)
def register(
    user_in: UserRegister,
    db: Session = Depends(get_db),
):
    # --------------------------------------------------------
    # Check existing email
    # --------------------------------------------------------

    existing_user = (
        db.query(User)
        .filter(
            User.email == user_in.email.lower()
        )
        .first()
    )

    if existing_user:
        raise HTTPException(
            status_code=400,
            detail="Email already registered",
        )

    # --------------------------------------------------------
    # Create user
    # --------------------------------------------------------

    user = User(
        email=user_in.email.lower(),
        hashed_password=get_password_hash(
            user_in.password
        ),
        first_name=user_in.first_name.strip(),
        last_name=user_in.last_name.strip(),
        phone=user_in.phone,
        role=UserRole.BUSINESS_OWNER,
        is_active=True,
        is_verified=True,
        auth_provider="local",
        provider_user_id=None,
    )

    db.add(user)
    db.flush()

    # --------------------------------------------------------
    # Create business
    #
    # unique_code is generated by PostgreSQL server default.
    # DO NOT manually set unique_code here.
    # --------------------------------------------------------

    business = Business(
        owner_id=user.id,
        name=user_in.business_name.strip(),
        business_type=user_in.business_type,
        industry=user_in.industry,
        email=(
            user_in.business_email.lower()
            if user_in.business_email
            else None
        ),
        phone=user_in.business_phone,
        address=user_in.address,
        city=user_in.city,
        state=user_in.state,
        country=user_in.country,
        pincode=user_in.pincode,
        tax_type=user_in.tax_type,
        tax_id_gst=user_in.tax_id_gst,
        pan=user_in.pan,
        business_registration_number=(
            user_in.business_registration_number
        ),
    )

    db.add(business)
    db.flush()

    # --------------------------------------------------------
    # Commit
    # --------------------------------------------------------

    db.commit()

    db.refresh(user)
    db.refresh(business)

    # --------------------------------------------------------
    # Tokens
    # --------------------------------------------------------

    access_token = create_access_token(
        user.id,
        role=user.role.value,
        business_id=business.id,
    )

    refresh_token = create_refresh_token(
        user.id,
    )

    return {
        "access_token": access_token,
        "refresh_token": refresh_token,
        "token_type": "bearer",
        "user": user,
        "business": {
            "id": business.id,
            "unique_code": business.unique_code,
            "name": business.name,
            "currency": business.currency,
            "currency_symbol": business.currency_symbol,
        },
    }


