@router.post(
    "/social-login",
    response_model=Token,
)
def social_login(
    request: SocialLoginRequest,
    db: Session = Depends(get_db),
):
    """Authenticate a user with a verified Google ID token."""
    provider = request.provider.strip().lower()

    if provider != "google":
        raise HTTPException(status_code=400, detail="Only Google authentication is configured")

    if not request.id_token.strip():
        raise HTTPException(status_code=400, detail="Google identity token is required")

    google_client_id = getattr(settings, "GOOGLE_CLIENT_ID", None)
    if not google_client_id:
        raise HTTPException(status_code=500, detail="Google authentication is not configured")

    try:
        google_user = id_token.verify_oauth2_token(
            request.id_token,
            google_requests.Request(),
            google_client_id,
        )
    except ValueError:
        raise HTTPException(status_code=401, detail="Invalid or expired Google identity token")

    provider_user_id = google_user.get("sub")
    email = google_user.get("email")
    email_verified = google_user.get("email_verified", False)

    if not provider_user_id or not email:
        raise HTTPException(status_code=401, detail="Google account information is incomplete")

    if not email_verified:
        raise HTTPException(status_code=403, detail="Google email is not verified")

    email = email.lower().strip()
    first_name = (google_user.get("given_name") or google_user.get("name", "").split(" ")[0] or "Google").strip()
    last_name = (google_user.get("family_name") or "").strip()
    avatar_url = google_user.get("picture")

    user = db.query(User).filter(User.email == email).first()

    if not user:
        raise HTTPException(
            status_code=404,
            detail="No VyaparX account exists for this Google email. Please register first.",
        )

    if not user.is_active:
        raise HTTPException(status_code=403, detail="Account is deactivated")

    if user.auth_provider == "local":
        raise HTTPException(
            status_code=409,
            detail="An account with this email already exists using email/password login. Please use your password.",
        )

    if user.auth_provider != "google":
        raise HTTPException(status_code=409, detail="This account uses a different authentication provider")

    if user.provider_user_id != provider_user_id:
        raise HTTPException(status_code=409, detail="Google account does not match the registered account")

    user.first_name = first_name
    user.last_name = last_name
    user.avatar_url = avatar_url
    user.is_verified = True

    db.add(user)
    db.commit()
    db.refresh(user)

    return create_auth_response(user)


