@router.get(
    "/users",
    response_model=List[UserResponse],
)
def list_business_users(
    current_user: User = Depends(
        RoleChecker(
            [
                UserRole.BUSINESS_OWNER,
                UserRole.MANAGER,
            ]
        )
    ),
    db: Session = Depends(get_db),
):
    business = get_user_business(
        current_user
    )

    if not business:
        return [current_user]

    business_users = (
        db.query(User)
        .join(BusinessUser)
        .filter(
            BusinessUser.business_id
            == business.id
        )
        .all()
    )

    # Owner may not have a BusinessUser row.
    if (
        current_user.role
        == UserRole.BUSINESS_OWNER
        and current_user not in business_users
    ):
        business_users.insert(
            0,
            current_user,
        )

    return business_users


