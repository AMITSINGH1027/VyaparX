    refresh_token = create_refresh_token(
        user.id,
    )

    return {
        "access_token": access_token,
        "refresh_token": refresh_token,
        "token_type": "bearer",
        "user": user,
        "business": {
            "id": business.id,
            "unique_code": business.unique_code,
            "name": business.name,
            "currency": business.currency,
            "currency_symbol": business.currency_symbol,
        },
    }


