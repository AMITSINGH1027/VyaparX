@router.post(
    "/users",
    response_model=UserResponse,
)
def create_employee_user(
    user_in: UserCreateByAdmin,
    current_user: User = Depends(
        RoleChecker(
            [UserRole.BUSINESS_OWNER]
        )
    ),
    db: Session = Depends(get_db),
):
    # --------------------------------------------------------
    # Owner must have business
    # --------------------------------------------------------

    if not current_user.owned_business:
        raise HTTPException(
            status_code=400,
            detail=(
                "No active business registered "
                "for current user"
            ),
        )

    # --------------------------------------------------------
    # Check email
    # --------------------------------------------------------

    existing = (
        db.query(User)
        .filter(
            User.email
            == user_in.email.lower()
        )
        .first()
    )

    if existing:
        raise HTTPException(
            status_code=400,
            detail="Email already registered",
        )

    business = (
        current_user.owned_business
    )

    # --------------------------------------------------------
    # Create user
    # --------------------------------------------------------

    new_user = User(
        email=user_in.email.lower(),
        hashed_password=get_password_hash(
            user_in.password
        ),
        first_name=user_in.first_name.strip(),
        last_name=user_in.last_name.strip(),
        phone=user_in.phone,
        role=user_in.role,
        is_active=True,
        is_verified=True,
        auth_provider="local",
        provider_user_id=None,
    )

    db.add(new_user)
    db.flush()

    # --------------------------------------------------------
    # Business membership
    # --------------------------------------------------------

    membership = BusinessUser(
        business_id=business.id,
        user_id=new_user.id,
    )

    db.add(membership)

    # --------------------------------------------------------
    # Optional employee record
    # --------------------------------------------------------

    employee = Employee(
        business_id=business.id,
        user_id=new_user.id,
        first_name=new_user.first_name,
        last_name=new_user.last_name,
        email=new_user.email,
        phone=new_user.phone,
        designation="Staff",
        department=(
            user_in.department
            or "Sales"
        ),
        joining_date=date.today(),
        is_active="true",
    )

    db.add(employee)

    db.commit()
    db.refresh(new_user)

    return new_user